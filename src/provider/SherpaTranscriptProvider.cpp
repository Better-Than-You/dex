constexpr int SampleRate = 16000;
constexpr int VadWindowSize = 512;
constexpr int TickIntervalMs = 30;
constexpr float MaxSpeechSeconds = 30.0f;
constexpr float MinSpeechSeconds = 0.25f;
constexpr int MaxActiveSamples = SampleRate * 30;
constexpr int PreRollSamples = SampleRate * 3 / 5; // 600 ms before VAD detection

/// Fixed lengths the final VAD buffer is zero-padded up to before the single
/// offline decode. ONNX Runtime sizes its arena per input tensor shape, so
/// feeding it arbitrary VAD lengths makes it allocate a fresh bucket for every
/// utterance and RSS climbs into the gigabytes (the ~1.9 GB arena bloat). Four
/// shapes only ever exist, and zero padding is silence, so it does not change
/// the transcript.
constexpr std::array<std::size_t, 4> DecodeBuckets = {32000, 64000, 128000, 240000};

std::size_t bucketedSampleCount(std::size_t count)
{
    for (const std::size_t bucket : DecodeBuckets) {
        if (count <= bucket)
            return bucket;
    }
    return std::max(count, DecodeBuckets.back());
}

/// sherpa-onnx accepts `provider[:config_path]`, so `cpu:<file>` keeps the CPU
/// execution provider while pointing it at an ONNX Runtime session config.
/// Not caching freed buffers keeps the single-shot session from holding its
/// peak scratch memory between utterances.
QString writeOrtCpuConfig()
{
    static const QByteArray contents = QByteArrayLiteral(
        "# Generated by Dex: do not let the single-shot Parakeet session cache\n"
        "# freed activation buffers.\n"
        "EnableCpuMemArena=0\n"
        "EnableMemPattern=0\n");

    QStringList candidates;
    const QString runtimeDir = QString::fromLocal8Bit(qgetenv("XDG_RUNTIME_DIR"));
    if (!runtimeDir.isEmpty())
        candidates << runtimeDir + QStringLiteral("/dex-ort-cpu.conf");
    candidates << QStringLiteral("/tmp/dex-ort-cpu.conf");

    for (const QString &path : candidates) {
        // Skip the write when the file already holds exactly this content; the
        // reload path calls back here on every restart.
        QFile existing(path);
        if (existing.open(QIODevice::ReadOnly) && existing.readAll() == contents)
            return path;

        QSaveFile file(path);
        if (!file.open(QIODevice::WriteOnly) || file.write(contents) != contents.size()
            || !file.commit()) {
            continue;
        }
        return path;
    }

    qWarning("Dex ASR: could not write the ONNX Runtime CPU config file; "
             "the CPU memory arena stays enabled.");
    return {};
}
